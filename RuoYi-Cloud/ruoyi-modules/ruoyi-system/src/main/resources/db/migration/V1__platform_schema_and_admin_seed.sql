CREATE TABLE IF NOT EXISTS `p_email_token` (
  `id` bigint NOT NULL COMMENT '主键，服务生成的正整数 ID',
  `created_at` datetime(3) NOT NULL COMMENT '创建时间，UTC',
  `updated_at` datetime(3) NOT NULL COMMENT '更新时间，UTC',
  `user_id` bigint NULL COMMENT '关联sys_user.user_id；注册前允许为空',
  `email` varchar(254) NOT NULL COMMENT '规范化邮箱',
  `purpose` varchar(24) NOT NULL COMMENT 'VERIFY_EMAIL/RESET_PASSWORD',
  `token_hash` binary(32) NOT NULL COMMENT '一次性随机令牌摘要，不存明文验证码',
  `expires_at` datetime(3) NOT NULL COMMENT '到期时间',
  `consumed_at` datetime(3) NULL COMMENT '成功消费时间',
  `failed_attempts` int NOT NULL DEFAULT 0 COMMENT '默认0；失败尝试次数',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_p_email_token_1` (`token_hash`),
  KEY `idx_p_email_token_1` (`email`, `purpose`, `created_at`),
  KEY `idx_p_email_token_2` (`expires_at`),
  CONSTRAINT `ck_p_email_token_id` CHECK (`id` > 0),
  CONSTRAINT `ck_p_email_token_user_id` CHECK (`user_id` > 0),
  CONSTRAINT `ck_p_email_token_purpose` CHECK (`purpose` IN ('VERIFY_EMAIL', 'RESET_PASSWORD')),
  CONSTRAINT `ck_p_email_token_failed_attempts` CHECK (`failed_attempts` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='邮箱验证与密码重置';

