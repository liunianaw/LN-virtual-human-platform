  `name` varchar(100) COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '凭证显示名称',
  `public_id` varchar(48) NOT NULL COMMENT '对外可见且全局唯一的凭证标识',
  `secret_hash` binary(32) NOT NULL COMMENT '高熵Secret摘要或带服务端pepper的摘要',
  `hash_key_version` varchar(32) NOT NULL COMMENT '摘要方案/pepper版本',
  `display_suffix` varchar(8) NOT NULL COMMENT '脱敏显示后缀',
  `scopes` json NOT NULL COMMENT '本Key接入权限词表；APPLICATION存sessions:*，不存S运行权限',
  `status` varchar(20) NOT NULL COMMENT 'ACTIVE/DISABLED/DELETED',
  `expires_at` datetime(3) NULL COMMENT '可选有效期',
  `revoked_at` datetime(3) NULL COMMENT '撤销时间',
  `last_used_at` datetime(3) NULL COMMENT '最近使用，异步合并更新',
  `auth_epoch` bigint NOT NULL DEFAULT 1 COMMENT '默认1；轮换、停用、撤销递增，重新启用不复活旧授权',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_p_access_key_1` (`public_id`),
  KEY `idx_p_access_key_1` (`account_id`, `key_type`, `status`),
  KEY `idx_p_access_key_2` (`application_id`, `status`),
  CONSTRAINT `ck_p_access_key_id` CHECK (`id` > 0),
  CONSTRAINT `ck_p_access_key_account_id` CHECK (`account_id` > 0),
  CONSTRAINT `ck_p_access_key_application_id` CHECK (`application_id` > 0),
  CONSTRAINT `ck_p_access_key_key_type` CHECK (`key_type` IN ('MANAGEMENT', 'APPLICATION')),
  CONSTRAINT `ck_p_access_key_status` CHECK (`status` IN ('ACTIVE', 'DISABLED', 'DELETED')),
  CONSTRAINT `ck_p_access_key_auth_epoch` CHECK (`auth_epoch` > 0),
  CONSTRAINT `ck_p_access_key_application` CHECK ((`key_type` = 'MANAGEMENT' AND `application_id` IS NULL) OR (`key_type` = 'APPLICATION' AND `application_id` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='管理Key与Application Secret';

